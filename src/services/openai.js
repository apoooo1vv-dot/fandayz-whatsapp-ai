/**
 * الكلمات التي تُفعّل التحويل للموظف البشري
 */
const HANDOFF_KEYWORDS = [
  "موظف بشري", "أريد إنسان", "مدير", "مشرف",
  "ابغى احد", "ابغى موظف", "كلمني احد", "بشري",
  "تحدث مع شخص", "لا أريد بوت", "وكيل", "إنسان",
];

function checkHandoffRequest(message) {
  const lowerMessage = message.toLowerCase();
  return HANDOFF_KEYWORDS.some(k => lowerMessage.includes(k.toLowerCase()));
}

/**
 * استخراج بيانات العميل (هوية + جوال)
 */
function detectCustomerData(text) {
  const data = {};
  // رقم الهوية الوطنية (10 أرقام تبدأ بـ 1 أو 2)
  const idMatch = text.match(/\b[12]\d{9}\b/);
  if (idMatch) data.nationalId = idMatch[0];
  // رقم الجوال السعودي
  const phoneMatch = text.match(/\b(05\d{8}|5\d{8}|\+9665\d{8}|009665\d{8})\b/);
  if (phoneMatch) data.phone = phoneMatch[0];
  return Object.keys(data).length > 0 ? data : null;
}

/**
 * الحصول على رد من AI مع System Prompt الكامل
 */
async function getAIResponse(userMessage, conversationHistory = [], customer = null, packages = []) {
  try {
    // بناء System Prompt مع معلومات العميل الحالية
    let systemPrompt = FANDAYZ_SYSTEM_PROMPT;

    // إضافة معلومات العميل الحالية إذا كانت موجودة
    if (customer) {
      const customerContext = [];
      if (customer.name) customerContext.push(`اسم العميل: ${customer.name}`);
      if (customer.selected_package) customerContext.push(`الباقة المختارة: ${customer.selected_package}`);
      if (customer.national_id) customerContext.push(`رقم الهوية: ${customer.national_id}`);
      if (customer.tabby_tamara_number) customerContext.push(`رقم الجوال في تابي/تمارا: ${customer.tabby_tamara_number}`);
      if (customer.status) customerContext.push(`حالة الطلب: ${customer.status}`);

      if (customerContext.length > 0) {
        systemPrompt += `\n\n====================\nمعلومات العميل الحالية\n====================\n${customerContext.join('\n')}`;
      }
    }

    // إضافة الباقات من قاعدة البيانات إذا كانت مختلفة
    if (packages && packages.length > 0) {
      const pkgList = packages.map(p =>
        `الباقة ${p.id}: صافي التحويل ${p.net_transfer} ريال | إجمالي الأقساط ${p.total_installments} ريال | القسط الشهري ${p.monthly_installment} ريال`
      ).join('\n');
      systemPrompt += `\n\n====================\nالباقات المتوفرة (من قاعدة البيانات)\n====================\n${pkgList}`;
    }

    const messages = [
      { role: "system", content: systemPrompt },
      ...conversationHistory.slice(-12), // آخر 12 رسالة للسياق
      { role: "user", content: userMessage },
    ];

    const response = await openai.chat.completions.create({
      model: "gpt-4o-mini",
      messages,
      max_tokens: 500,
      temperature: 0.15, // منخفض لضمان الاتساق
    });

    let reply = response.choices[0]?.message?.content?.trim();
    if (!reply) throw new Error("لم يُرجع OpenAI ردًا");

    // التحقق من وجود HANDOFF_TRIGGER
    let shouldHandoff = false;
    if (reply.includes("[HANDOFF_TRIGGER]")) {
      shouldHandoff = true;
      reply = reply.replace("[HANDOFF_TRIGGER]", "").trim();
    }

    // استخراج بيانات العميل من رسالته
    const customerData = detectCustomerData(userMessage);

    // تفعيل Handoff تلقائياً إذا أرسل الهوية والجوال معاً
    if (customerData?.nationalId && customerData?.phone) {
      shouldHandoff = true;
    }

    console.log(`[OpenAI] ✅ رد (${reply.length} حرف) | Handoff: ${shouldHandoff}`);
    return { reply, shouldHandoff, customerData };

  } catch (error) {
    console.error("[OpenAI] ❌ خطأ:", error.message);
    throw error;
  }
}

module.exports = { getAIResponse, checkHandoffRequest, detectCustomerData };
